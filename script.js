        function getFilteredVocab() {
            const q = (document.getElementById('vocab-search')?.value || '').trim().toLowerCase();
            const lvl = document.getElementById('vocab-filter-level')?.value || 'all';
            const les = document.getElementById('vocab-filter-lesson')?.value || 'all';
            const top = document.getElementById('vocab-filter-topic')?.value || 'all';
            const stFilter = document.getElementById('vocab-filter-state')?.value || 'all';

            return VOCABULARY_DB.filter(w => {
                const effLevel = getWordEffectiveLevel(w);
                if (lvl !== 'all' && String(effLevel) !== String(lvl)) return false;
                if (les !== 'all' && w.lesson !== les) return false;
                if (top !== 'all' && w.topic !== top) return false;
                const p = window.learnerState.vocabProgress[w.id] || { state: 0, bookmarked: false };
                if (stFilter === 'bookmarked' && !p.bookmarked) return false;
                if (stFilter !== 'all' && stFilter !== 'bookmarked' && String(p.state) !== String(stFilter)) return false;
                if (q) {
                    const match = w.hanzi.includes(q) || w.pinyin.toLowerCase().includes(q) || w.viet.toLowerCase().includes(q) || w.pos.toLowerCase().includes(q);
                    if (!match) return false;
                }
                return true;
            });
        }


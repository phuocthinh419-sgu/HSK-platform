        // Chuyển đổi dữ liệu PCM16 từ Gemini TTS sang định dạng WAV chuẩn
        function pcm16Base64ToWavUrl(base64Data, sampleRate = 24000) {
            const binaryStr = atob(base64Data);
            const len = binaryStr.length;
            const pcmBytes = new Uint8Array(len);
            for (let i = 0; i < len; i++) {
                pcmBytes[i] = binaryStr.charCodeAt(i);
            }
            const wavHeader = new ArrayBuffer(44);
            const view = new DataView(wavHeader);
            const writeStr = (offset, str) => {
                for (let i = 0; i < str.length; i++) view.setUint8(offset + i, str.charCodeAt(i));
            };
            writeStr(0, 'RIFF');
            view.setUint32(4, 36 + pcmBytes.byteLength, true);
            writeStr(8, 'WAVE');
            writeStr(12, 'fmt ');
            view.setUint32(16, 16, true);
            view.setUint16(20, 1, true); // PCM
            view.setUint16(22, 1, true); // Mono
            view.setUint32(24, sampleRate, true);
            view.setUint32(28, sampleRate * 2, true);
            view.setUint16(32, 2, true);
            view.setUint16(34, 16, true);
            writeStr(36, 'data');
            view.setUint32(40, pcmBytes.byteLength, true);

            const blob = new Blob([wavHeader, pcmBytes], { type: 'audio/wav' });
            return URL.createObjectURL(blob);
        }

        async function playWithGeminiNeuralTTS(text, rate = 0.95) {
            const cacheKey = text.trim();
            if (geminiAudioCache[cacheKey]) {
                return playAudioUrlWithFastTimeout(geminiAudioCache[cacheKey], rate, 1000);
            }
            const apiKey = "";
            const apiUrl = `https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash-preview-tts:generateContent?key=${apiKey}`;
            const promptText = `请用自然、清晰、温和的标准北京普通话（带准确四声声调，适合HSK汉语听力与跟读教学）朗读以下内容：${cacheKey}`;
            const payload = {
                contents: [{ parts: [{ text: promptText }] }],
                generationConfig: {
                    responseModalities: ["AUDIO"],
                    speechConfig: {
                        voiceConfig: {
                            prebuiltVoiceConfig: { voiceName: "Kore" }
                        }
                    }
                }
            };
            const res = await fetch(apiUrl, {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify(payload)
            });
            const result = await res.json();
            const part = result?.candidates?.[0]?.content?.parts?.[0];
            const audioData = part?.inlineData?.data;
            const mimeType = part?.inlineData?.mimeType || "audio/L16;rate=24000";
            if (!audioData) throw new Error("No Gemini TTS audio data");
            const rateMatch = mimeType.match(/rate=(\d+)/);
            const sampleRate = rateMatch ? parseInt(rateMatch[1], 10) : 24000;
            const wavUrl = pcm16Base64ToWavUrl(audioData, sampleRate);
            geminiAudioCache[cacheKey] = wavUrl;
            return playAudioUrlWithFastTimeout(wavUrl, rate, 1200);
        }

        // Phát URL âm thanh với cơ chế Fast-Timeout (1100ms) để không bao giờ bị treo 5-10s
        function playAudioUrlWithFastTimeout(url, rate = 0.95, timeoutMs = 1100) {
            return new Promise((resolve, reject) => {
                let settled = false;
                const timer = setTimeout(() => {
                    if (!settled) {
                        settled = true;
                        if (currentAudioPlayer) {
                            currentAudioPlayer.pause();
                            currentAudioPlayer = null;
                        }
                        reject(new Error("Audio stream timeout exceeded"));
                    }
                }, timeoutMs);

                try {
                    if (currentAudioPlayer) {
                        currentAudioPlayer.pause();
                        currentAudioPlayer = null;
                    }
                    if ('speechSynthesis' in window && window.speechSynthesis.speaking) {
                        window.speechSynthesis.cancel();
                    }
                    const audio = new Audio(url);
                    currentAudioPlayer = audio;
                    audio.preservesPitch = true;
                    audio.mozPreservesPitch = true;
                    audio.webkitPreservesPitch = true;
                    audio.playbackRate = Math.max(0.55, Math.min(1.25, rate));

                    audio.onplaying = () => {
                        if (!settled) {
                            settled = true;
                            clearTimeout(timer);
                            resolve(true);
                        }
                    };
                    audio.onerror = (err) => {
                        if (!settled) {
                            settled = true;
                            clearTimeout(timer);
                            reject(err);
                        }
                    };
                    const playPromise = audio.play();
                    if (playPromise !== undefined) {
                        playPromise.catch(err => {
                            if (!settled) {
                                settled = true;
                                clearTimeout(timer);
                                reject(err);
                            }
                        });
                    }
                } catch (e) {
                    clearTimeout(timer);
                    reject(e);
                }
            });
        }


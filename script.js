        function evaluateWritingSubmission(taskId) {
            const task = WRITING_TASKS_DB.find(x => x.id === taskId);
            const inp = document.getElementById(`w-task-inp-${taskId}`);
            const fb = document.getElementById(`w-task-fb-${taskId}`);
            if (!task || !inp || !fb) return;
            const rawOriginal = inp.value.trim();
            if (!rawOriginal) {
                fb.innerHTML = `<span class="text-rose-600 font-semibold">Vui lòng nhập bài viết của bạn trước khi chấm.</span>`;
                return;
            }

            const matchedKeywords = task.keywords.filter(k => rawOriginal.includes(k));
            const exactMatch = normalizeChineseSentence(rawOriginal) === normalizeChineseSentence(task.expected);
            const isGood = exactMatch || matchedKeywords.length >= Math.ceil(task.keywords.length * 0.6);

            window.learnerState.skillStats.writing.attempts += 1;
            if (isGood) {
                window.learnerState.skillStats.writing.correct += 1;
                window.learnerState.dailyQuests.readWrite += 1;
                matchedKeywords.forEach(hz => {
                    const v = VOCABULARY_DB.find(x => x.hanzi === hz);
                    if (v) updateWordSRSandMetric(v.id, 'write', true, 4);
                });
                awardRealXP(15, `Hoàn thành bài viết: ${task.actType}`);
            } else {
                recordLearningError("Luyện Viết", task.actType, rawOriginal, task.expected, task.keywords.join(', '));
            }

            // Always preserve original answer & improved version in learnerState
            const submissionRecord = {
                id: "wsub_" + Date.now(),
                time: new Date().toLocaleString('vi-VN'),
                taskTitle: task.actType,
                originalText: rawOriginal,
                improvedText: task.expected,
                keywordsUsed: matchedKeywords,
                passed: isGood,
                feedbackVi: exactMatch
                    ? "Chính xác tuyệt đối về chữ Hán, trật tự từ và cấu trúc ngữ pháp."
                    : `Đã sử dụng ${matchedKeywords.length}/${task.keywords.length} từ khóa mục tiêu (${matchedKeywords.join(', ') || 'chưa có'}). Hãy đối chiếu trật tự từ và ngữ pháp với phiên bản chuẩn.`
            };
            window.learnerState.skillStats.writing.submissions.unshift(submissionRecord);
            persistState();

            fb.innerHTML = `
                <div class="p-3.5 rounded-xl border ${isGood ? 'bg-emerald-50 border-emerald-200 text-emerald-900' : 'bg-amber-50 border-amber-200 text-amber-900'} space-y-1.5">
                    <div class="font-extrabold">${isGood ? '<i class="fa-solid fa-circle-check mr-1"></i>Đánh giá tốt!' : '<i class="fa-solid fa-pen mr-1"></i>Cần cải thiện cấu trúc/từ vựng'}</div>
                    <div><strong>Câu trả lời ban đầu của bạn (Đã lưu):</strong> <span class="hanzi-font font-bold">${rawOriginal}</span></div>
                    <div><strong>Phiên bản chuẩn / Cải thiện tự nhiên:</strong> <span class="hanzi-font font-bold text-emerald-800">${task.expected}</span></div>
                    <div><strong>Nhận xét chi tiết:</strong> ${submissionRecord.feedbackVi}</div>
                </div>
            `;

            const logEl = document.getElementById('writing-history-log');
            if (logEl) logEl.innerHTML = renderWritingHistoryItems();
        }


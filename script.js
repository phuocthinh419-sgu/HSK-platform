        function checkAutoObjective(idx, userVal, correctVal, extraNote, vietTrans) {
            const fb = document.getElementById(`auto-fb-${idx}`);
            const ok = normalizeChineseSentence(userVal) === normalizeChineseSentence(correctVal);
            if (ok) {
                // Promote vocabulary metrics for words used in this new context
                ["觉得", "认为", "因为", "所以", "但是"].forEach(hz => {
                    const v = VOCABULARY_DB.find(x => x.hanzi === hz);
                    if (v) updateWordSRSandMetric(v.id, 'newContext', true, 3);
                });
                awardRealXP(12, "Hoàn thành bài tập tự động trong ngữ cảnh mới");
                if (fb) fb.innerHTML = `<div class="p-3 rounded-xl bg-emerald-50 border border-emerald-200 text-emerald-900 font-semibold"><i class="fa-solid fa-circle-check mr-1"></i>Chính xác! Đáp án: <span class="hanzi-font">${correctVal}</span>.<br><span class="font-normal">Nội dung/Giải thích: ${extraNote} ${vietTrans ? '• ' + vietTrans : ''}</span></div>`;
            } else {
                recordLearningError("Tự Động Tạo Bài Tập", `Bài tập ngữ cảnh mới #${idx + 1}`, userVal, correctVal, extraNote);
                if (fb) fb.innerHTML = `<div class="p-3 rounded-xl bg-rose-50 border border-rose-200 text-rose-900 font-semibold"><i class="fa-solid fa-circle-xmark mr-1"></i>Chưa đúng. Đáp án chuẩn là: <span class="hanzi-font">${correctVal}</span>.<br><span class="font-normal">${extraNote}</span></div>`;
            }
        }

        function checkAutoSpeaking(idx) {
            const inp = document.getElementById(`auto-spk-inp-${idx}`);
            const fb = document.getElementById(`auto-fb-${idx}`);
            if (!inp || !fb) return;
            const val = inp.value.trim();
            const matchedWords = ["觉得", "认为", "因为", "所以", "但是"].filter(w => val.includes(w));
            if (matchedWords.length === 0) {
                fb.innerHTML = `<div class="p-2.5 rounded-xl bg-rose-50 text-rose-700 font-semibold">Hãy sử dụng ít nhất 1 từ mục tiêu (觉得, 认为, 因为, 所以, 但是) trong câu trả lời của bạn!</div>`;
                return;
            }
            window.learnerState.skillStats.speaking.attempts += 1;
            window.learnerState.skillStats.speaking.correct += 1;
            matchedWords.forEach(hz => {
                const v = VOCABULARY_DB.find(x => x.hanzi === hz);
                if (v) updateWordSRSandMetric(v.id, 'newContext', true, 4);
            });
            awardRealXP(15, `Vận dụng chủ động từ ${matchedWords.join(', ')}`);
            fb.innerHTML = `<div class="p-3 rounded-xl bg-emerald-50 border border-emerald-200 text-emerald-900"><i class="fa-solid fa-check-circle mr-1"></i><strong>Rất tốt!</strong> Bạn đã chủ động vận dụng từ <strong>${matchedWords.join(', ')}</strong> trong câu: <span class="hanzi-font font-bold">"${val}"</span>.</div>`;
        }


        function normalizePinyinPlain(str) {
            return (str || '').toLowerCase()
                .normalize("NFD").replace(/[\u0300-\u036f]/g, "")
                .replace(/\s+/g, '');
        }

        function submitRecallAnswer(wordId, chosenMeaning) {
            const w = VOCABULARY_DB.find(x => x.id === wordId);
            if (!w) return;
            const pyInp = document.getElementById('recall-pinyin-input')?.value || '';
            const pyMatch = normalizePinyinPlain(pyInp) === normalizePinyinPlain(w.pinyin);
            const meaningMatch = chosenMeaning === w.viet;

            if (meaningMatch) {
                updateWordSRSandMetric(w.id, 'meaning', true, pyMatch ? 3 : 2);
                if (pyMatch) updateWordSRSandMetric(w.id, 'pinyin', true, 3);
                window.learnerState.dailyQuests.recallVocab += 1;
                awardRealXP(pyMatch ? 12 : 8, `Nhớ chính xác từ ${w.hanzi}`);
            } else {
                updateWordSRSandMetric(w.id, 'meaning', false, 1);
                recordLearningError("Kho Từ Vựng", `Nhớ nghĩa từ ${w.hanzi} (${w.pinyin})`, chosenMeaning, w.viet, w.hanzi);
                showToast(`Chưa đúng! ${w.hanzi} (${w.pinyin}) nghĩa là: "${w.viet}". Đã thêm vào lịch ôn SRS.`, "rose");
            }
            activeRecallIndex++;
            renderCurrentRecallQuestion();
        }


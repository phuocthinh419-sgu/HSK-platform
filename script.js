        function startSpeechRecognitionForInput(inputId, onCompleteCallback) {
            const SR = window.SpeechRecognition || window.webkitSpeechRecognition;
            if (!SR) {
                showToast("Trình duyệt hiện tại không có SpeechRecognition API. Bạn có thể đọc to và nhập văn bản vào ô để kiểm tra cấu trúc câu.", "amber");
                return;
            }
            try {
                const rec = new SR();
                rec.lang = 'zh-CN';
                rec.interimResults = false;
                showToast("Đang lắng nghe tiếng Trung (zh-CN)... Hãy bắt đầu nói!", "emerald");
                rec.onresult = (event) => {
                    const transcript = event.results[0][0].transcript;
                    const inp = document.getElementById(inputId);
                    if (inp) inp.value = transcript;
                    if (onCompleteCallback) onCompleteCallback();
                };
                rec.onerror = () => {
                    showToast("Không nhận diện được âm thanh. Hãy thử lại hoặc nhập trực tiếp.", "amber");
                };
                rec.start();
            } catch (e) {
                showToast("Không thể khởi động micro trong khung hiện tại.", "amber");
            }
        }

        function evaluatePronunciationMatch(itemId, targetZh) {
            const inp = document.getElementById(`spk-input-${itemId}`);
            const fb = document.getElementById(`spk-fb-${itemId}`);
            if (!inp || !fb) return;
            const spoken = normalizeChineseSentence(inp.value);
            const target = normalizeChineseSentence(targetZh);
            if (!spoken) {
                fb.innerHTML = `<span class="text-rose-600 font-semibold">Hãy thu âm hoặc nhập câu bạn vừa đọc để đối chiếu.</span>`;
                return;
            }
            let matchChars = 0;
            const missingChars = [];
            for (const ch of target) {
                if (spoken.includes(ch)) {
                    matchChars++;
                } else {
                    missingChars.push(ch);
                }
            }
            const scorePct = Math.round((matchChars / Math.max(1, target.length)) * 100);
            window.learnerState.skillStats.speaking.attempts += 1;

            if (scorePct >= 75) {
                window.learnerState.skillStats.speaking.correct += 1;
                window.learnerState.dailyQuests.listenSpeak += 1;
                VOCABULARY_DB.forEach(v => {
                    if (target.includes(v.hanzi)) {
                        updateWordSRSandMetric(v.id, 'sentence', true, 3);
                    }
                });
                awardRealXP(12, `Hoàn thành Shadowing (${scorePct}% khớp chữ Hán)`);
            } else {
                recordLearningError("Luyện Nói (Shadowing)", targetZh, inp.value, targetZh, missingChars.join(', '));
            }
            persistState();

            fb.innerHTML = `
                <div class="p-3 rounded-xl border ${scorePct >= 75 ? 'bg-emerald-50 border-emerald-200 text-emerald-900' : 'bg-amber-50 border-amber-200 text-amber-900'} space-y-1">
                    <div class="font-bold">Độ khớp âm tiết & chữ Hán: ${scorePct}% (${matchChars}/${target.length} chữ)</div>
                    <div><strong>Câu bạn đọc/nhập:</strong> <span class="hanzi-font">${inp.value}</span></div>
                    ${missingChars.length > 0 ? `<div><strong>Các chữ cần chú ý phát âm rõ hơn:</strong> <span class="hanzi-font font-bold text-rose-600">${missingChars.join(' • ')}</span></div>` : `<div class="text-emerald-700 font-semibold">Bạn đã phát âm khớp toàn bộ chữ Hán trong câu mẫu!</div>`}
                    <div class="text-[11px] text-slate-500 pt-1 border-t border-black/5">
                        *Lưu ý kỹ thuật minh bạch: Hệ thống đối chiếu văn bản nhận diện từ giọng nói (Web Speech-to-Text zh-CN) và cấu trúc câu thực tế; không giả lập chấm tần số âm học nếu thiết bị chỉ nhập văn bản.
                    </div>
                </div>
            `;
        }


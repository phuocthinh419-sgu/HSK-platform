        // SRS Scheduling intervals: 1 -> 3 -> 7 -> 14 -> 30 days
        function updateWordSRSandMetric(wordId, metricKey, isSuccess, promoteStateMin = 1) {
            const entry = ensureVocabEntry(wordId);
            entry.historyCount += 1;
            if (isSuccess) {
                if (metricKey && entry.metrics.hasOwnProperty(metricKey)) {
                    entry.metrics[metricKey] = true;
                }
                if (entry.state < promoteStateMin) {
                    entry.state = promoteStateMin;
                }
                // Count how many metrics achieved to promote to state 3 or 4 automatically based on real mastery
                const achievedCount = Object.values(entry.metrics).filter(Boolean).length;
                if (achievedCount >= 5 && (entry.metrics.sentence || entry.metrics.newContext)) {
                    entry.state = 4; // Có thể sử dụng chủ động
                } else if (achievedCount >= 3 && entry.state < 3) {
                    entry.state = 3; // Có thể tự nhớ lại
                }
                const intervals = [1, 3, 7, 14, 30];
                const currentIdx = intervals.indexOf(entry.intervalDays);
                const nextDays = currentIdx === -1 ? 1 : intervals[Math.min(intervals.length - 1, currentIdx + 1)];
                entry.intervalDays = nextDays;
                entry.nextReview = Date.now() + nextDays * 86400 * 1000;
            } else {
                // Reset SRS interval to 1 day & mark due now
                entry.intervalDays = 1;
                entry.nextReview = Date.now();
                entry.bookmarked = true;
            }
            persistState();
        }


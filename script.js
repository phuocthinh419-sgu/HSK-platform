        function submitReadingAnswer(passageId, qIdx, chosenOpt) {
            const passage = READING_DB.find(x => x.id === passageId);
            if (!passage || !passage.questions[qIdx]) return;
            const qObj = passage.questions[qIdx];
            const isCor = chosenOpt === qObj.answer;
            readingUserAnswers[`${passageId}_${qIdx}`] = { ans: chosenOpt, correct: isCor };

            // Check if all questions in this passage have been answered to unlock translation in test mode
            const allAnswered = passage.questions.every((_, i) => !!readingUserAnswers[`${passageId}_${i}`]);
            if (allAnswered) {
                completedReadingPassages[passageId] = true;
            }

            window.learnerState.skillStats.reading.attempts += 1;
            if (isCor) {
                window.learnerState.skillStats.reading.correct += 1;
                window.learnerState.dailyQuests.readWrite += 1;
                passage.keyVocab.forEach(hz => {
                    const v = VOCABULARY_DB.find(x => x.hanzi === hz);
                    if (v) updateWordSRSandMetric(v.id, 'char', true, 2);
                });
                awardRealXP(10, `Trả lời đúng câu hỏi Đọc hiểu (${passage.title})`);
            } else {
                recordLearningError("Luyện Đọc", `${passage.title} - ${qObj.q}`, chosenOpt, qObj.answer, passage.keyVocab.join(', '));
            }
            persistState();
            renderReadingSection();
        }

